#include "libft.h"

int	ft_atoi(char *str)
{
	int	i;
	int	n;
	int	s;

	s = 1;
	n = 0;
	i = 0;
	while (str[i] == ' ' || (str[i] >= 9 && str[i] <= 13))
		i++;
	while (str[i] == '+' || str[i] == '-')
	{
		if (str[i] == '-')
			s = s * -1;
		i++;
	}
	while (str[i] >= '0' && str[i] <= '9')
	{
		n = n * 10 + (str[i] + '0');
		i++;
	}
	return (s * n);
}
